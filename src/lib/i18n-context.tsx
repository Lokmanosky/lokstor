interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
  isRtl: boolean;
  dir: 'rtl' | 'ltr';
  localizeCategory: (cat?: string) => string;
  formatCurrency: (amount: number | string) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'ar',
  setLang: () => {},
  t: (k) => k,
  isRtl: true,
  dir: 'rtl',
  localizeCategory: (c) => c || '',
  formatCurrency: (a) => `${a} د.ج`,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>('ar');

  useEffect(() => {
    const saved = localStorage.getItem('lokstor_lang') as Lang;
    if (saved && translations[saved]) {
      setLang(saved);
      document.documentElement.lang = saved;
      document.documentElement.dir = saved === 'ar' ? 'rtl' : 'ltr';
    }
  }, []);

  const handleSetLang = (newLang: Lang) => {
    setLang(newLang);
    localStorage.setItem('lokstor_lang', newLang);
    document.documentElement.lang = newLang;
    document.documentElement.dir = newLang === 'ar' ? 'rtl' : 'ltr';
  };

  const t = (key: string): string => {
    return translations[lang]?.[key] || translations['ar']?.[key] || key;
  };

  const localizeCategory = (cat?: string): string => {
    if (!cat) return '';
    const lower = cat.toLowerCase().trim();
    if (lower.includes('ألعاب') || lower.includes('لعب') || lower.includes('game') || lower === 'games') {
      return t('category.games');
    }
    if (lower.includes('رقمي') || lower.includes('digital')) {
      return t('category.digital');
    }
    if (lower.includes('اشتراك') || lower.includes('sub')) {
      return t('category.subs');
    }
    if (lower.includes('برامج') || lower.includes('تطبيق') || lower.includes('software') || lower.includes('app')) {
      return t('category.software');
    }
    if (lower.includes('دورة') || lower.includes('دورات') || lower.includes('course')) {
      return t('category.courses');
    }
    if (lower.includes('قالب') || lower.includes('قوالب') || lower.includes('template')) {
      return t('category.templates');
    }
    if (lower.includes('كتاب') || lower.includes('كتب') || lower.includes('book') || lower.includes('pdf')) {
      return t('category.books');
    }
    if (lower.includes('حساب') || lower.includes('account')) {
      return t('category.accounts');
    }
    if (lower === 'all' || lower === 'الكل') {
      return t('category.all');
    }
    return cat;
  };

  const formatCurrency = (amount: number | string): string => {
    const num = typeof amount === 'number' ? amount : parseFloat(amount) || 0;
    const formattedNum = num.toLocaleString(lang === 'ar' ? 'ar-DZ' : lang === 'fr' ? 'fr-FR' : 'en-US');
    return `${formattedNum} ${t('common.currency')}`;
  };

  const isRtl = lang === 'ar';
  const dir = isRtl ? 'rtl' : 'ltr';

  return (
    <I18nContext.Provider value={{
      lang,
      setLang: handleSetLang,
      t,
      isRtl,
      dir,
      localizeCategory,
      formatCurrency
    }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useTranslation = () => useContext(I18nContext);
